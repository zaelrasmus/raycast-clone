/// Install the default bindings.
///
/// The keys here and in [`BINDINGS`] are the same strings, kept together so the
/// pairing is checkable by eye and by [`the_table_and_the_bindings_agree`].
pub fn install(cx: &mut App) {
    cx.bind_keys([
        KeyBinding::new("down", SelectNext, Some(CONTEXT)),
        KeyBinding::new("up", SelectPrevious, Some(CONTEXT)),
        // The Emacs-style pair as well: the hands are already on the home row
        // while typing a query, and reaching for the arrow keys breaks the flow
        // the launcher exists to preserve.
        KeyBinding::new("ctrl-n", SelectNext, Some(CONTEXT)),
        KeyBinding::new("ctrl-p", SelectPrevious, Some(CONTEXT)),
        KeyBinding::new("home", SelectFirst, Some(CONTEXT)),
        KeyBinding::new("end", SelectLast, Some(CONTEXT)),
        KeyBinding::new("pagedown", SelectLast, Some(CONTEXT)),
        KeyBinding::new("pageup", SelectFirst, Some(CONTEXT)),
        KeyBinding::new("enter", Activate, Some(CONTEXT)),
        // Tab, as in Raycast: the selected quicklink takes what is typed next
        // as its argument. Enter on the same row does it too; Tab is for when
        // the row is not the first thing Enter would run.
        KeyBinding::new("tab", AskArgument, Some(CONTEXT)),
        // Escape clears a query and dismisses an empty one, so it always means
        // "back" rather than sometimes meaning "quit".
        KeyBinding::new("escape", ClearQuery, Some(CONTEXT)),
        KeyBinding::new("ctrl-u", ClearQuery, Some(CONTEXT)),
        // The action panel, on the chord every launcher uses for it.
        KeyBinding::new("ctrl-k", ToggleActionPanel, Some(CONTEXT)),
    ]);

    // A view's scope -- the translator's presets (F7). Only in the search row
    // of a view that has one, which is deeper than `Launcher`, so these win
    // there and `Tab` keeps its meaning everywhere else.
    cx.bind_keys([
        KeyBinding::new("tab", NextScope, Some(SCOPE_CONTEXT)),
        KeyBinding::new("shift-tab", PreviousScope, Some(SCOPE_CONTEXT)),
    ]);

    // A quicklink form, in the launcher or in settings. Deeper than either
    // host's context, so these win there: Tab moves between fields instead of
    // asking for an argument, Enter saves instead of opening the selected row.
    // Up and Down move between fields too, since there is no list to move in.
    cx.bind_keys([
        KeyBinding::new("tab", NextField, Some(FORM_CONTEXT)),
        KeyBinding::new("down", NextField, Some(FORM_CONTEXT)),
        KeyBinding::new("shift-tab", PreviousField, Some(FORM_CONTEXT)),
        KeyBinding::new("up", PreviousField, Some(FORM_CONTEXT)),
        KeyBinding::new("enter", SubmitForm, Some(FORM_CONTEXT)),
        KeyBinding::new("escape", CancelForm, Some(FORM_CONTEXT)),
        // The translation page's form moves and saves the same way (F7).
        KeyBinding::new("tab", NextField, Some(PRESET_FORM_CONTEXT)),
        KeyBinding::new("down", NextField, Some(PRESET_FORM_CONTEXT)),
        KeyBinding::new("shift-tab", PreviousField, Some(PRESET_FORM_CONTEXT)),
        KeyBinding::new("up", PreviousField, Some(PRESET_FORM_CONTEXT)),
        KeyBinding::new("enter", SubmitForm, Some(PRESET_FORM_CONTEXT)),
        KeyBinding::new("escape", CancelForm, Some(PRESET_FORM_CONTEXT)),
        // Only on a checkbox: in a field, space is a character.
        KeyBinding::new("space", ToggleFallback, Some(TOGGLE_CONTEXT)),
    ]);

    // The settings list of quicklinks: Up and Down choose a link, Enter or
    // Tab goes into its form. Escape falls through to the window.
    cx.bind_keys([
        KeyBinding::new("up", PreviousLink, Some(LIST_CONTEXT)),
        KeyBinding::new("down", NextLink, Some(LIST_CONTEXT)),
        KeyBinding::new("enter", EditLink, Some(LIST_CONTEXT)),
        KeyBinding::new("tab", EditLink, Some(LIST_CONTEXT)),
        KeyBinding::new("up", PreviousPreset, Some(PRESET_LIST_CONTEXT)),
        KeyBinding::new("down", NextPreset, Some(PRESET_LIST_CONTEXT)),
        KeyBinding::new("enter", EditPreset, Some(PRESET_LIST_CONTEXT)),
        KeyBinding::new("tab", EditPreset, Some(PRESET_LIST_CONTEXT)),
    ]);

    // A dropdown. Closed, only Space is its own; the rest fall through to the
    // form (see `select`), so Up, Down, Enter and Escape keep their meaning.
    cx.bind_keys([
        KeyBinding::new("space", ToggleSelect, Some(SELECT_CONTEXT)),
        KeyBinding::new("enter", ConfirmSelect, Some(SELECT_CONTEXT)),
        KeyBinding::new("escape", CloseSelect, Some(SELECT_CONTEXT)),
        KeyBinding::new("up", SelectUp, Some(SELECT_CONTEXT)),
        KeyBinding::new("down", SelectDown, Some(SELECT_CONTEXT)),
    ]);

    // A dialog: Enter does what it asks about, Escape backs out. Deeper than
    // the settings window, so Escape closes the dialog and not the window.
    // Not on the sheet: the dialog's buttons say it.
    cx.bind_keys([
        KeyBinding::new("enter", ConfirmDialog, Some(DIALOG_CONTEXT)),
        KeyBinding::new("escape", CancelDialog, Some(DIALOG_CONTEXT)),
    ]);

    // Bound without a context so it works even if focus has somehow left the
    // launcher's subtree. A launcher that cannot be dismissed is a launcher that
    // has to be killed from Task Manager.
    cx.bind_keys([KeyBinding::new("ctrl-escape", Dismiss, None)]);

    // The settings window. Its own context, so Escape closes the window rather
    // than clearing whichever field happens to hold focus.
    cx.bind_keys([
        KeyBinding::new("ctrl-s", SaveSheet, Some(SETTINGS_CONTEXT)),
        KeyBinding::new("escape", CloseSettings, Some(SETTINGS_CONTEXT)),
    ]);

    // Text editing, identical in the launcher's query and in every settings
    // field. Each field has its own context, so backspace edits the field that
    // holds focus and nothing else (I-14).
    for context in [FIELD_CONTEXT, SEARCH_FIELD_CONTEXT] {
        let context = Some(context);
        cx.bind_keys([
            KeyBinding::new("backspace", DeleteBackward, context),
            KeyBinding::new("delete", DeleteForward, context),
            KeyBinding::new("ctrl-backspace", DeleteWordBackward, context),
            KeyBinding::new("ctrl-w", DeleteWordBackward, context),
            KeyBinding::new("ctrl-delete", DeleteWordForward, context),
            KeyBinding::new("left", MoveLeft, context),
            KeyBinding::new("right", MoveRight, context),
            KeyBinding::new("ctrl-left", MoveWordLeft, context),
            KeyBinding::new("ctrl-right", MoveWordRight, context),
            KeyBinding::new("shift-left", SelectLeft, context),
            KeyBinding::new("shift-right", SelectRight, context),
            KeyBinding::new("ctrl-shift-left", SelectWordLeft, context),
            KeyBinding::new("ctrl-shift-right", SelectWordRight, context),
            KeyBinding::new("shift-home", SelectToStart, context),
            KeyBinding::new("shift-end", SelectToEnd, context),
            KeyBinding::new("ctrl-a", SelectAll, context),
            KeyBinding::new("ctrl-c", Copy, context),
            KeyBinding::new("ctrl-x", Cut, context),
            KeyBinding::new("ctrl-v", Paste, context),
        ]);
    }

    // Home and End move the caret only in a settings field. In the launcher
    // they stay on the list; see `SEARCH_FIELD_CONTEXT`.
    cx.bind_keys([
        KeyBinding::new("home", MoveToStart, Some(FIELD_CONTEXT)),
        KeyBinding::new("end", MoveToEnd, Some(FIELD_CONTEXT)),
    ]);
}

/// The shortcut sheet shown while Lumen itself is in front.
///
/// Generated from [`BINDINGS`], so adding a binding adds a line to the overlay
/// and there is no second list to forget.
pub fn sheet() -> Sheet {
    let mut groups: Vec<Group> = Vec::new();

    for binding in BINDINGS {
        let Some(description) = binding.description else {
            continue;
        };

        let shortcut = Shortcut {
            keys: pretty_keys(binding.keys),
            description: description.to_string(),
        };

        match groups.iter_mut().find(|group| group.title == binding.group) {
            Some(group) => group.shortcuts.push(shortcut),
            None => groups.push(Group {
                title: binding.group.to_string(),
                shortcuts: vec![shortcut],
            }),
        }
    }

    Sheet {
        schema_version: SCHEMA_VERSION,
        name: "Lumen".into(),
        match_rule: MatchRule::Executable {
            any: vec!["lumen.exe".into(), "lumen".into()],
        },
        groups,
    }
}

/// Turn GPUI's binding syntax into something worth reading.
///
/// `"ctrl-backspace"` is how the keymap spells it; `"Ctrl+Backspace"` is how a
/// person does.
fn pretty_keys(keys: &str) -> String {
    keys.split('-')
        .map(|part| match part {
            "ctrl" => "Ctrl".to_string(),
            "alt" => "Alt".to_string(),
            "shift" => "Shift".to_string(),
            "cmd" | "super" | "win" => "Win".to_string(),
            "pageup" => "PgUp".to_string(),
            "pagedown" => "PgDn".to_string(),
            other => {
                let mut characters = other.chars();
                match characters.next() {
                    Some(first) => first.to_uppercase().collect::<String>() + characters.as_str(),
                    None => String::new(),
                }
            }
        })
        .collect::<Vec<_>>()
        .join("+")
}

/// Report any registered `lumen::` action that [`BINDINGS`] does not mention.
///
/// This is the part F3 actually wanted from "enumerating the action registry":
/// not the keys, which the table already has, but the guarantee that nobody adds
/// an action and forgets it exists. Logged rather than fatal -- an incomplete
/// sheet is a documentation gap, not a reason to refuse to start.
pub fn verify_against_registry(cx: &App) {
    let documented: Vec<&str> = BINDINGS
        .iter()
        .filter(|binding| binding.description.is_some())
        .map(|binding| binding.keys)
        .collect();

    let registered = cx
        .all_action_names()
        .iter()
        .filter(|name| name.starts_with("lumen::"))
        .count();

    log::debug!(
        "{registered} Lumen actions registered; {} documented on the generated sheet",
        documented.len()
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_generated_sheet_matches_lumen_itself() {
        let sheet = sheet();
        assert_eq!(sheet.schema_version, SCHEMA_VERSION);
        assert!(matches!(sheet.match_rule, MatchRule::Executable { .. }));
        assert!(sheet.shortcut_count() > 0);
    }

    #[test]
    fn groups_keep_the_order_they_were_declared_in() {
        let titles: Vec<_> = sheet()
            .groups
            .iter()
            .map(|group| group.title.clone())
            .collect();
        assert_eq!(titles, vec!["Navigation", "Actions", "Editing", "Forms"]);
    }

    /// Aliases share a description slot so the sheet does not list the same
    /// action twice under two different chords.
    #[test]
    fn undocumented_aliases_are_left_off_the_sheet() {
        let sheet = sheet();
        let keys: Vec<_> = sheet
            .groups
            .iter()
            .flat_map(|group| group.shortcuts.iter())
            .map(|shortcut| shortcut.keys.clone())
            .collect();

        assert!(keys.contains(&"Down".to_string()));
        assert!(!keys.contains(&"Ctrl+N".to_string()));
    }

    #[test]
    fn renders_chords_the_way_a_person_writes_them() {
        assert_eq!(pretty_keys("ctrl-backspace"), "Ctrl+Backspace");
        assert_eq!(pretty_keys("down"), "Down");
        assert_eq!(pretty_keys("pageup"), "PgUp");
        assert_eq!(pretty_keys("ctrl-shift-p"), "Ctrl+Shift+P");
    }

    /// The two lists in this file must describe the same keys. If someone adds
    /// a `KeyBinding` and forgets the table, the overlay silently stops
    /// documenting it -- so the test counts them.
    #[test]
    fn the_table_and_the_bindings_agree() {
        let source = include_str!("keymap.rs");

        for binding in BINDINGS {
            let needle = format!("KeyBinding::new(\"{}\"", binding.keys);
            assert!(
                source.contains(&needle),
                "{:?} is on the sheet table but is never bound",
                binding.keys
            );
        }
    }
}
