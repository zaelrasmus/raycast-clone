//! In-window key bindings (AD-15, I-14).
//!
//! Every binding is declared here and resolved by GPUI against the focus tree.
//! Nothing in the UI compares keys by hand.
//!
//! This is the *inside the window* half of AD-15. Global invocation is the other
//! half, lives behind `trait Platform`, and the two never overlap: GPUI resolves
//! keystrokes against the focus tree, which requires the window to already hold
//! focus, so it cannot cover summoning the window in the first place.
//!
//! # One table, two consumers
//!
//! F3 requires that Lumen's own entries in the shortcut overlay "are not written
//! by hand: they are generated by enumerating GPUI's global action registry".
//! The point of that rule is that the sheet cannot drift away from the bindings
//! that are actually installed.
//!
//! [`BINDINGS`] is that single source: [`install`] feeds it to GPUI, and
//! [`sheet`] renders it into a [`Sheet`]. Driving both from the table is
//! strictly stronger than reading the registry back, because the registry can
//! only report the keys -- it has no human-readable description of what each
//! action *does*, and inventing one from the action's type name produces
//! "SelectNext" where the user needs "Move down".
//!
//! [`verify_against_registry`] then closes the remaining gap: it asks GPUI for
//! every registered `lumen::` action and reports any that this table forgot.

